def ku_question_ids(
    selection_paths: Sequence[Path],
    dataset: Path,
) -> tuple[list[str], list[str]]:
    """Return (ms-slice KU ids, new KU ids) from the two selection files."""
    records = record_index(dataset)
    ms_ku: list[str] = []
    new_ku: list[str] = []
    for selection_path in selection_paths:
        payload = json.loads(selection_path.read_text(encoding="utf-8"))
        target = ms_ku if "test20-ms" in selection_path.name else new_ku
        for sample_id in payload["sample_ids"]:
            record = records.get(sample_id)
            if record is not None and record.get("question_type") == "knowledge-update":
                target.append(sample_id)
    return ms_ku, new_ku


def load_gold_by_question(gold_path: Path) -> dict[str, GoldPair]:
    from benchmarks.mechanism.gold import load_gold_pairs

    return {pair.question_id: pair for pair in load_gold_pairs(gold_path).pairs}


