"""Eval A: deterministic mechanism metrics over replayed stores (spec §4.3).

All metrics here are pure recomputations over sealed artifacts and replayed
stores; no LLM calls are made. M1/M5 are computed per gold pair when gold is
provided; without gold the partial metrics report action counts, R1-R7
diagnostic bucketing, contradiction-score distribution, fact-slot presence,
and M3 new-side recall (the old side is NA until gold annotation exists).

Provenance of ``runs/mechanism/evala/metrics.partial.json``:

    The artifact is regenerated by ``compute_metrics_from_online`` (CLI:
    ``python -m benchmarks.mechanism.eval_a --source-run <run> --out <path>
    --dataset <dataset> --ms-selection <selection>``). Action counts come
    from the online-persisted ``samples/<id>.json -> ingestion.etec.actions``
    field, NOT from offline replay; the ms run ``model_cache`` does not cover
    all replay embeddings (candidate-generation embedding path diverges from
    the online run, ``tests/mechanism/test_replay.py:212`` skips on
    ``OfflineCacheMiss``). M3 new_recall comes from the finalized
    ``retrieval.jsonl -> packed_items.evidence_refs.raw_turn_id`` union vs the
    dataset ``answer_session_ids`` (the old side is NA without gold; only
    new_recall is computed and the artifact records ``caliber_limitation``).
    ``summarize_replays`` / ``compute_m1`` / ``compute_m5`` (replay-based) are
    retained for per-decision detail but the ms run replay has a known
    cache-miss limitation; the partial artifact prefers the online counts.
"""

