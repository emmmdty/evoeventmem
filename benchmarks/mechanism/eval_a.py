_RAW_TURN_RE = re.compile(r"^(.*):\d+$")


def session_id_from_turn_id(turn_id: str) -> str:
    """Map a raw turn id (``<session>:<index>``) to its session id."""
    match = _RAW_TURN_RE.match(turn_id)
    return match.group(1) if match else turn_id


def retrieved_session_ids(retrieval_row: Mapping[str, Any]) -> set[str]:
    """Union of session ids behind packed evidence raw turn ids."""
    session_ids: set[str] = set()
    for item in retrieval_row.get("packed_items", []):
        for ref in item.get("evidence_refs", []):
            raw_turn_id = ref.get("raw_turn_id")
            if raw_turn_id is None:
                continue
            session_ids.add(session_id_from_turn_id(str(raw_turn_id)))
    return session_ids


def _gold_side_sessions(gold: GoldPair, turn_ids: Sequence[str]) -> set[str]:
    return {session_id_from_turn_id(turn_id) for turn_id in turn_ids}


def compute_m3(
    retrieval_rows: Sequence[Mapping[str, Any]],
    dataset: Path,
    *,
    question_ids: Sequence[str],
    gold_by_question: Mapping[str, GoldPair] | None = None,
    methods: Sequence[str] = ("full", "event_no_etec", "etec", "vector_rag"),
) -> dict[str, Any]:
    """Compute per-question, per-method old/new recall and JERecall@8.

    The new side is the dataset's ``answer_session_ids`` (data-native). The
    old side comes from gold ``old_value_turn_ids`` when gold is provided;
    without gold the old side is NA for every question and JERecall is not
    computable (both sides required, spec §4.3).
    """
    records = record_index(dataset)
    rows_by_question: dict[str, dict[str, Mapping[str, Any]]] = {}
    for row in retrieval_rows:
        rows_by_question.setdefault(str(row["question_id"]), {})[str(row["method"])] = row

    per_question: dict[str, dict[str, Any]] = {}
    for question_id in question_ids:
        record = records.get(question_id)
        if record is None:
            raise ValueError(f"question {question_id} not in dataset")
        new_sessions = {
            str(session_id) for session_id in record.get("answer_session_ids", [])
        }
        gold = (gold_by_question or {}).get(question_id)
        old_sessions: set[str] | None = None
        if gold is not None:
            old_sessions = _gold_side_sessions(gold, gold.old_value_turn_ids)
        question_row: dict[str, Any] = {"new_sessions": sorted(new_sessions)}
        if old_sessions is not None:
            question_row["old_sessions"] = sorted(old_sessions)
        for method in methods:
            row = rows_by_question.get(question_id, {}).get(method)
            if row is None:
                question_row[method] = None
                continue
            retrieved = retrieved_session_ids(row)
            new_recall = len(retrieved & new_sessions) / len(new_sessions) if new_sessions else None
            old_recall: float | None = None
            je_recall: int | None = None
            if old_sessions is not None:
                if old_sessions:
                    old_recall = len(retrieved & old_sessions) / len(old_sessions)
                if old_recall is not None and new_recall is not None:
                    je_recall = int(old_recall > 0 and new_recall > 0)
            question_row[method] = {
                "old_recall": old_recall,
                "new_recall": new_recall,
                "je_recall@8": je_recall,
                "retrieved_session_count": len(retrieved),
            }
        per_question[question_id] = question_row

    summaries: dict[str, dict[str, Any]] = {}
    for method in methods:
        values = [per_question[q][method] for q in question_ids if per_question[q][method]]
        old_values = [v["old_recall"] for v in values if v["old_recall"] is not None]
        new_values = [v["new_recall"] for v in values if v["new_recall"] is not None]
        je_values = [v["je_recall@8"] for v in values if v["je_recall@8"] is not None]
        summaries[method] = {
            "questions_with_rows": len(values),
            "old_recall_mean": _mean(old_values) if old_values else None,
            "old_side_na_questions": len(values) - len(old_values),
            "new_recall_mean": _mean(new_values) if new_values else None,
            "je_recall@8": _mean(je_values) if je_values else None,
            "je_computable_questions": len(je_values),
        }
    return {"per_question": per_question, "methods": summaries}


def _mean(values: Sequence[float]) -> float:
    return float(sum(values) / len(values))


