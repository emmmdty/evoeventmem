SUPERSEDE_CONTRADICTION_MIN = 0.7
M1_CONTENT_COVERAGE_MIN = 0.5

_R3_HITS = frozenset({"missing_fact_effective_time", "equal_fact_effective_time"})
_R7_HITS = frozenset({"disjoint_temporal_intervals"})
_R5_HITS = frozenset({"explicit_multi_valued_slot"})

R_BUCKET_ORDER = (
    "R3_effective_time_missing_or_equal",
    "R5_multi_valued",
    "R7_merge_temporal_disjoint",
    "R1_structural_fact_slot_absent",
    "R4_extraction_miss",
    "R2_contradiction_below_threshold",
    "R6_candidate_bounded_out",
    "unclassified",
)


def has_fact_slot(metadata: Mapping[str, Any]) -> bool:
    value = metadata.get("fact_slot")
    return isinstance(value, str) and bool(value)


def bucket_decision(decision: ReplayDecision) -> str:
    """Classify one decision into the pre-registered R1-R7 root causes.

    Rule-hit buckets are decided first (they can only fire when fact slots
    exist), then the structural R1 absence check, then the remaining causes.
    """
    rule_hits = frozenset(decision.rule_hits)
    if rule_hits & _R3_HITS:
        return "R3_effective_time_missing_or_equal"
    if rule_hits & _R5_HITS or decision.features.get("multi_valued"):
        return "R5_multi_valued"
    if rule_hits & _R7_HITS:
        return "R7_merge_temporal_disjoint"
    if "no_active_candidate" in rule_hits or decision.target_memory_id is None:
        return "R6_candidate_bounded_out"
    if not has_fact_slot(decision.source_metadata) or (
        decision.target_metadata is not None and not has_fact_slot(decision.target_metadata)
    ):
        return "R1_structural_fact_slot_absent"
    if "missing_source_evidence" in rule_hits:
        return "R4_extraction_miss"
    if float(decision.features.get("contradiction_score", 0.0)) < SUPERSEDE_CONTRADICTION_MIN:
        return "R2_contradiction_below_threshold"
    return "unclassified"


def summarize_replays(replays: Mapping[str, SampleReplay]) -> dict[str, Any]:
    """Partial Eval A block: actions, contradiction distribution, R buckets."""
    total_actions: Counter[str] = Counter()
    non_add_buckets: Counter[str] = Counter()
    all_buckets: Counter[str] = Counter()
    contradiction_histogram: Counter[float] = Counter()
    rule_hits: Counter[str] = Counter()
    decision_count = 0
    fact_slot_memories = 0
    fact_value_memories = 0
    event_memories = 0
    for replay in replays.values():
        total_actions.update(replay.actions)
        fact_slot_memories += replay.snapshot_events_with_fact_slot
        fact_value_memories += replay.snapshot_events_with_fact_value
        event_memories += replay.snapshot_event_count
        for decision in replay.decisions:
            decision_count += 1
            bucket = bucket_decision(decision)
            all_buckets[bucket] += 1
            if decision.action != "ADD":
                non_add_buckets[bucket] += 1
            contradiction_histogram[float(decision.features.get("contradiction_score", 0.0))] += 1
            rule_hits.update(decision.rule_hits)
    zero_contradictions = contradiction_histogram.get(0.0, 0)
    return {
        "actions": dict(sorted(total_actions.items())),
        "decision_count": decision_count,
        "non_add_decision_count": sum(non_add_buckets.values()),
        "contradiction_score": {
            "zero_count": zero_contradictions,
            "nonzero_count": decision_count - zero_contradictions,
            "histogram": {
                format(value, ".4f"): count
                for value, count in sorted(contradiction_histogram.items())
            },
            "max_value": max(contradiction_histogram) if contradiction_histogram else None,
        },
        "rule_hits": dict(sorted(rule_hits.items())),
        "fact_slot_presence": {
            "snapshot_events": event_memories,
            "events_with_fact_slot": fact_slot_memories,
            "events_with_fact_value": fact_value_memories,
        },
        "r1_r7_all_decisions": {bucket: all_buckets.get(bucket, 0) for bucket in R_BUCKET_ORDER},
        "r1_r7_non_add": {
            bucket: non_add_buckets.get(bucket, 0) for bucket in R_BUCKET_ORDER
        },
    }


